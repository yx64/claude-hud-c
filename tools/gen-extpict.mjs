// Generates extpict.h, the Extended_Pictographic ranges from emoji-data.txt. utf8proc marks only
// assigned code points; the property also covers reserved ones, and the upstream width math (a
// regex on node) sees those too. Checks the result against this node before writing it.
import fs from 'node:fs';

const [emojiData, out] = process.argv.slice(2);
const ranges = [];
for (const raw of fs.readFileSync(emojiData, 'utf8').split('\n')) {
  const line = raw.replace(/#.*/, '').trim();
  if (!line) continue;
  const [cps, prop] = line.split(';').map((s) => s.trim());
  if (prop !== 'Extended_Pictographic') continue;
  const [a, b] = cps.split('..').map((h) => parseInt(h, 16));
  ranges.push([a, b ?? a]);
}
ranges.sort((x, y) => x[0] - y[0]);
const merged = [];
for (const r of ranges) {
  const last = merged.at(-1);
  if (last && r[0] <= last[1] + 1) last[1] = Math.max(last[1], r[1]);
  else merged.push([...r]);
}
const inTable = (c) => merged.some(([a, b]) => c >= a && c <= b);
const re = /\p{Extended_Pictographic}/u;
for (let c = 0; c < 0x110000; c++) {
  if (c >= 0xd800 && c <= 0xdfff) continue;
  if (inTable(c) !== re.test(String.fromCodePoint(c))) throw new Error(`mismatch at ${c.toString(16)}`);
}
const body = merged.map(([a, b]) => `{0x${a.toString(16)}, 0x${b.toString(16)}}`).join(',\n    ');
fs.writeFileSync(out, `// Generated by gen-extpict.mjs from emoji-data.txt (Unicode ${process.versions.unicode}). Do not edit.
#pragma once
#include <stdint.h>
static const uint32_t EXTPICT[][2] = {
    ${body},
};
static inline bool is_extpict(uint32_t c) {
    int lo = 0, hi = (int)(sizeof EXTPICT / sizeof *EXTPICT) - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        if (c < EXTPICT[mid][0]) hi = mid - 1;
        else if (c > EXTPICT[mid][1]) lo = mid + 1;
        else return true;
    }
    return false;
}
`);
console.log(`ranges ${merged.length}`);
